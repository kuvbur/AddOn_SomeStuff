#include "CommandBase.hpp"

#if defined(ServerMainVers_2500)

// -----------------------------------------------------------------------------
// Возвращает пространство имён, общее для всех JSON-команд аддона.
// -----------------------------------------------------------------------------
GS::String CommandNamespace () { return "SomeStuffCommand"; }

// -----------------------------------------------------------------------------
// Создаёт базовую команду и сохраняет режим использования общей схемы.
// -----------------------------------------------------------------------------
CommandBase::CommandBase (CommonSchema commonSchema) : mCommonSchema (commonSchema) {}

// -----------------------------------------------------------------------------
// Возвращает пространство имён JSON-команды.
// -----------------------------------------------------------------------------
GS::String CommandBase::GetNamespace () const { return CommandNamespace (); }

// -----------------------------------------------------------------------------
// Назначает выполнение команды в главном потоке Archicad.
// -----------------------------------------------------------------------------
API_AddOnCommandExecutionPolicy CommandBase::GetExecutionPolicy () const {
    return API_AddOnCommandExecutionPolicy::ScheduleForExecutionOnMainThread;
}

// -----------------------------------------------------------------------------
// Обрабатывает ошибку проверки ответа команды.
// -----------------------------------------------------------------------------
void CommandBase::OnResponseValidationFailed (const GS::ObjectState & /*response*/) const {}

// -----------------------------------------------------------------------------
// Возвращает определения схемы ответа команды, если они предусмотрены.
// -----------------------------------------------------------------------------
GS::Optional<GS::UniString> CommandBase::GetSchemaDefinitions () const { return GS::Optional<GS::UniString> (); }

// -----------------------------------------------------------------------------
// Возвращает схему входных параметров команды, если она предусмотрена.
// -----------------------------------------------------------------------------
GS::Optional<GS::UniString> CommandBase::GetInputParametersSchema () const { return GS::Optional<GS::UniString> (); }

// -----------------------------------------------------------------------------
// Возвращает схему ответа команды, если она предусмотрена.
// -----------------------------------------------------------------------------
GS::Optional<GS::UniString> CommandBase::GetResponseSchema () const { return GS::Optional<GS::UniString> (); }

// -----------------------------------------------------------------------------
// Формирует ответ с кодом и текстом ошибки команды.
// -----------------------------------------------------------------------------
GS::ObjectState CreateErrorResponse (GSErrCode errorCode, const GS::UniString &errorMessage) {
    GS::ObjectState os;
    os.Add ("error", GS::ObjectState ("code", errorCode));
    os.Add ("message", errorMessage);
    return os;
}

// -----------------------------------------------------------------------------
// Формирует успешный ответ команды.
// -----------------------------------------------------------------------------
GS::ObjectState CreateSuccessResponse () { return GS::ObjectState ("success", true); }

#endif // defined (ServerMainVers_2500)
