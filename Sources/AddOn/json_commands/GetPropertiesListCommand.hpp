#if !defined(GETPROPERTIESLISTCOMMAND_HPP)
#define GETPROPERTIESLISTCOMMAND_HPP
#include "CommonFunction.hpp"
#include "json_commands/CommandBase.hpp"

// -----------------------------------------------------------------------------
// Команда получения значений свойств для выделенных элементов.
//
// Ответ содержит массив элементов, каждый с GUID и списком свойств.
// Свойства включают имя, тип значения, GUID свойства и строковое значение.
// Команда использует кэш, если он валиден, чтобы избежать повторных чтений.
// -----------------------------------------------------------------------------
class GetPropertiesListCommand : public ReadOnlyCommand {
  public:
    GetPropertiesListCommand ();

    // -------------------------------------------------------------------------
    // @return Имя команды JSON.
    // -------------------------------------------------------------------------
    virtual GS::String GetName () const override;

    // -------------------------------------------------------------------------
    // @return Схема входных параметров. В этой команде нет входных параметров.
    // -------------------------------------------------------------------------
    virtual GS::Optional<GS::UniString> GetInputParametersSchema () const override;

    // -------------------------------------------------------------------------
    // @return Схема ответа. В этой команде схема не задаётся.
    // -------------------------------------------------------------------------
    virtual GS::Optional<GS::UniString> GetResponseSchema () const override;

    // -------------------------------------------------------------------------
    // Выполняет команду и возвращает значения свойств выделенных элементов.
    // -------------------------------------------------------------------------
    virtual GS::ObjectState Execute (const GS::ObjectState &parameters,
                                     GS::ProcessControl &processControl) const override;
};

#endif // GETPROPERTIESLISTCOMMAND_HPP