#pragma once

#if defined(ServerMainVers_2500)

    #include "json_commands/CommandBase.hpp"

class SpecCommand : public CommandBase {
  public:
    // -----------------------------------------------------------------------------
    // Создаёт JSON-команду запуска построения спецификации.
    // -----------------------------------------------------------------------------
    SpecCommand ();

    // -----------------------------------------------------------------------------
    // Возвращает имя команды запуска построения спецификации.
    // -----------------------------------------------------------------------------
    GS::String GetName () const override;

    // -----------------------------------------------------------------------------
    // Возвращает схему параметров non-interactive запуска спецификации.
    // -----------------------------------------------------------------------------
    GS::Optional<GS::UniString> GetInputParametersSchema () const override;

    // -----------------------------------------------------------------------------
    // Возвращает схему ответа команды.
    // -----------------------------------------------------------------------------
    GS::Optional<GS::UniString> GetResponseSchema () const override;

    // -----------------------------------------------------------------------------
    // Запускает построение спецификации и возвращает длительность вызова.
    // -----------------------------------------------------------------------------
    GS::ObjectState Execute (const GS::ObjectState &parameters, GS::ProcessControl &processControl) const override;
};

#endif // defined (ServerMainVers_2500)