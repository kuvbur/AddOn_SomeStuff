#if !defined(HEALTHCOMMAND_HPP)
#define HEALTHCOMMAND_HPP
#include "CommandBase.hpp"
#include "CommonFunction.hpp"

// -----------------------------------------------------------------------------
// Health-команда для проверки работоспособности аддона.
//
// Возвращает текущий статус и версию аддона.
// -----------------------------------------------------------------------------
class HealthCommand : public ReadOnlyCommand
{
public:
    HealthCommand();
    
    // -------------------------------------------------------------------------
    // @return Имя команды JSON.
    // -------------------------------------------------------------------------
    virtual GS::String GetName() const override;

    // -------------------------------------------------------------------------
    // @return Схема входных параметров. В этой команде нет входных параметров.
    // -------------------------------------------------------------------------
    virtual GS::Optional<GS::UniString> GetInputParametersSchema() const override;

    // -------------------------------------------------------------------------
    // @return Схема ответа. В этой команде схема не задаётся.
    // -------------------------------------------------------------------------
    virtual GS::Optional<GS::UniString> GetResponseSchema() const override;

    // -------------------------------------------------------------------------
    // Выполняет команду и возвращает информацию о здоровье аддона.
    // -------------------------------------------------------------------------
    virtual GS::ObjectState Execute(const GS::ObjectState& parameters,
                                     GS::ProcessControl& processControl) const override;
};

#endif // HEALTHCOMMAND_HPP