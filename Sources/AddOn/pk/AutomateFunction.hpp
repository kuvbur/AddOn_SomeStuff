#pragma once
#if !defined(AUTOMATE_HPP)
    #define AUTOMATE_HPP
    #include "ACAPinc.h"

    #include "Helpers.hpp"
    #include "Sector2DData.h"

namespace AutoFunc {
    // Структура с отрезками для создания 3д документов
    struct SSectLine {
        double angz = 0;   // Угол отрезка
        double angz_1 = 0; // Угол подрезки начала отрезка
        double angz_2 = 0; // Угол подрезки конца отрезка
        Sector s;          // Отрезок для построения 3д сечения
        API_Guid elemguid = APINULLGuid;
        API_DatabaseUnId databaseUnId; // UnId базы данных созданного или найденного 3д документа
        API_Tranmat tm;                // Матрица преобразования координат, получена из API_3DProjectionInfo
    };

    // -----------------------------------------------------------------------------
    // Ищет в массиве отрезок, начало или конец которого находятся возле точки start.
    // Возвращает индекс элемента в массиве, а флаг isend показывает, что точка попала в конец отрезка.
    // -----------------------------------------------------------------------------
    bool GetNear (const GS::Array<Sector> &k, const Point2D &start, UInt32 &inx, bool &isend);

    // -----------------------------------------------------------------------------
    // Устанавливает подрезку по отрезку и возвращает параметры плоскостей сечения.
    // -----------------------------------------------------------------------------
    GSErrCode GetCuplane (const SSectLine sline, API_3DCutPlanesInfo &cutInfo, const double &depth);

    // -----------------------------------------------------------------------------
    // Устанавливает камеру перпендикулярно направлению angz и задаёт масштаб по осям x/y.
    // -----------------------------------------------------------------------------
    GSErrCode Get3DProjectionInfo (API_3DProjectionInfo &proj3DInfo, const double &angz, const double &koeff);

    // -----------------------------------------------------------------------------
    // Ищет 3D-документ по имени и ID; если не находит — создаёт новый.
    // Возвращает информацию о базе данных в dbInfo.
    // -----------------------------------------------------------------------------
    GSErrCode Get3DDocument (API_DatabaseInfo &dbInfo, const GS::UniString &name, const GS::UniString &id);

    // -----------------------------------------------------------------------------
    // Извлекает из морфа отрезки, сортирует их по удалению от startpos и возвращает массив сегментов.
    // -----------------------------------------------------------------------------
    GSErrCode GetSectLine (API_Guid &elemguid, GS::Array<SSectLine> &lines, GS::UniString &id, const Point2D &startpos);

    // -----------------------------------------------------------------------------
    // Создаёт 3D-документ для одного отрезка.
    // -----------------------------------------------------------------------------
    GSErrCode DoSect (
        SSectLine &sline, const GS::UniString &name, const GS::UniString &id, const double &koeff, const double &depth);

    // -----------------------------------------------------------------------------
    // Размещает на созданном отрезке элементы оформления и добавляет hotspot по его краям.
    // -----------------------------------------------------------------------------
    GSErrCode PlaceDocSect (SSectLine &sline, API_Element &elemline);

    // -----------------------------------------------------------------------------
    // Строит 3D-документы вдоль морфа.
    // -----------------------------------------------------------------------------
    void ProfileByLine ();

    // -----------------------------------------------------------------------------
    // Возвращает список GUID чертежей, отсортированных по именам.
    // -----------------------------------------------------------------------------
    GS::Array<API_Guid> GetDrawingsSort (const GS::Array<API_Guid> &elems);

    // -----------------------------------------------------------------------------
    // Выравнивает один чертёж по точкам и возвращает его новую позицию.
    // -----------------------------------------------------------------------------
    GSErrCode AlignOneDrawingsByPoints (const API_Guid &elemguid,
                                        API_DatabaseInfo &databasestart,
                                        API_WindowInfo &windowstart,
                                        const API_Coord &zeropos,
                                        API_Coord &startpos,
                                        API_Coord &drawingpos);

    // -----------------------------------------------------------------------------
    // Выравнивает чертежи по hotspot, найденным внутри их содержимого.
    // -----------------------------------------------------------------------------
    void AlignDrawingsByPoints ();
} // namespace AutoFunc

#endif
