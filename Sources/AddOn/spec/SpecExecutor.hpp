// Исполнитель этапов, работающих с моделью: создание элементов спецификации,
// их группировка и запуск GDL-скриптов. Планирование и сверка сюда не входят —
// они не обращаются к модели и остались в SpecPlanning.
//
// Назначение выделения (#228 R8.3): функция размещения не должна знать
// синтаксис правил (сбор имён свойств, флаги, разбор описания) и не должна
// пересчитывать группировку. Всё, что ей нужно, передаётся аргументами:
// словари строк, словарь записываемых свойств избранного, точку размещения и
// отчёт результата.
namespace Spec {

    // Размещает элементы спецификации на чертеже.
    //
    // Границы undo (проверено по коду, менять нельзя):
    //   - создание элементов и их группировка выполняются ВНУТРИ одной
    //     транзакции "Create Spec element";
    //   - GDL-скрипты выполняются ПОСЛЕ транзакции, поэтому отказ скрипта не
    //     откатывает уже созданный элемент. Это существующее поведение, а не
    //     дефект: втягивать скрипты внутрь транзакции нельзя, это расширило бы
    //     объём отката.
    //
    // Возвращаемое значение: APIERR_GENERAL, если отказ произошёл на этапе
    // создания (первичный этап). Отказы группировки и GDL в возврат не входят —
    // они учтены в runResult (см. SpecRunResult). Вызывающий возвращаемое
    // значение игнорирует, поэтому внешняя семантика запуска не меняется.
    //
    // paramOut - [OUT] свойства, записанные в созданные элементы. В него
    // попадают только подтверждённо созданные элементы: элемент, который
    // ACAPI_Element_Create не принял, записи не получает.
    // startpos - точка размещения, выбранная пользователем или заданная
    // аргументом запуска.
    GSErrCode PlaceElements (GS::Array<ElementDict> &elementstocreate,
                             ParamDictValue &paramToWrite,
                             ParamDictElement &paramOut,
                             Point2D &startpos,
                             SpecRunResult *runResult);
} // namespace Spec

#endif
