// Внутренняя модель планирования строк спецификации (блок R6).
//
// Разделение двух сущностей, которые до R6 существовали в одном типе Element:
//   SpecRow    — ИТОГОВАЯ строка: накопительный агрегат по ключу. То, что
//                сегодня лежит в Spec::Element и что уходит в сверку.
//   RuleContribution (вклад) — данные ОДНОГО источника в эту строку за один
//                проход цикла: что за источник, от какой группы пришёл,
//                какие значения прочитаны по слотам.
//
// Зачем отдельный вклад, а не «просто ещё одна структура»:
//   1. Цикл внутри PlanRuleRows смешивает три разных вопроса — «подходит ли
//      источник» (флаг/видимость/уникальные параметры), «что он вносит»
//      (значения по слотам) и «как это ложится в агрегат» (суммирование).
//      Вклад — это ровно второй вопрос, вынесенный отдельно, поэтому его
//      можно построить и проверить БЕЗ словаря элементов.
//   2. Слотовые значения у вклада могут оказаться НЕПОЛНЫМИ: Push выполняется
//      только при успешном чтении, поэтому число слотов известно лишь в цикле.
//      Именно это делает неполным и суммирование. Вклад фиксирует факт
//      неполноты (hasSumSlots/isComplete), не пытаясь её исправить — см. R6.3.
//   3. Источник вклада — API_Guid плюс имя группы. Для суммирования нужен
//      порядок первого представителя, поэтому источник хранится в порядке
//      добавления, как и раньше (R6.4 об этом отдельно).
//
// Чего вклад НЕ делает принципиально:
//   - Не накапливает вклады всех элементов модели в отдельном массиве.
//     Вклад живёт ровно один проход цикла и умирает вместе с ним; выход R6
//     прямо запрещает удвоение рабочего набора. Массив вкладов допускается
//     только в отдельном regression-режиме R6.5 и только для сравнения.
//   - Не меняет ключи строк, порядок первого представителя и арифметику
//     суммирования. Это работа R6.3/R6.4, здесь только описание.
namespace Spec {
    // Поле, которое не удалось прочитать, вместе с признанием того, является ли
    // это ошибкой элемента. isError = false — отказ не считается ошибкой
    // (чтение из состава конструкции либо продолжение строки GDL-массива).
    struct MissingField {
        GS::UniString rawname = EMPTYSTRING;
        bool isError = false;
    };

    // Статус включения источника в строку. Не bool, потому что у вклана есть
    // не два исхода: «не включён» и «включён частично» (прочитаны не все
    // слоты). Раньше это различалось неявно — по длине массивов элемента.
    enum class ContributionStatus : unsigned char {
        Excluded, // Источник не вносит вклад: не прошёл флаг/уникальность
        Empty,    // Включён, но ни одного значения прочитать не удалось
        Partial,  // Включён, прочитана часть слотов (Push только при успехе)
        Complete  // Включён, прочитаны все ожидаемые слоты
    };

    // Один вклад источника в итоговую строку (R6.2).
    struct RuleContribution {
        // --- источник (кто вносит) ---
        API_Guid source = APINULLGuid; // Элемент-источник
        UInt32 groupIndex = 0;         // Индекс группы в rule.groups

        // --- статус включения (R6.2: «статус включения») ---
        ContributionStatus status = ContributionStatus::Excluded;
        bool isIncluded = false; // Участвует ли вклад в агрегате (status != Excluded)

        // --- значения по слотам (R6.2: «значения по слотам») ---
        // Порядок элементов соответствует порядку binding.outSlots/sumSlots
        // группы, то есть порядку, который читает цикл. Длина может отличаться
        // от объявленной схемы: Push выполняется только при успешном чтении.
        GS::Array<ParamValue> outParam = {};    // Значения выходных слотов
        GS::Array<ParamValue> outSumParam = {}; // Значения суммируемых слотов

        // --- ошибки чтения, влияющие на агрегирование ---
        // Признак isError хранится НА КАЖДОЕ поле, а не общим флагом: отчёт
        // различает «отказ с fromMaterial» (ошибка элемента) и «отказ в строке
        // >1 массива GDL» (тихо), и поле-источник ошибки нужно знать, чтобы
        // пометить элемент и не повторить сообщение.
        GS::Array<MissingField> missingOut = {};  // Поля выхода, не прочитанные
        GS::Array<MissingField> missingSum = {};  // Поля суммы, не прочитанные
        GS::Array<MissingField> missingUnic = {}; // Уникальные параметры, не прочитанные
        bool hasReadError = false;                // Было ли неуспешное чтение с isError

        // --- ключ и производные величины ---
        GS::UniString key;        // Ключ строки: сцепка значений уникальных параметров
        GS::UniString keyOut;     // Склейка выходных значений (для out_param)
        bool hasKey = false;      // Ключ собран (hasUnic == true)
        bool outputsRead = false; // Фаза 2 выполнена (выходные слоты прочитаны)

        // Производные от размеров слотов — вынесены, чтобы статус не вычислялся
        // в нескольких местах. Считается от ФАКТИЧЕСКИХ размеров, как в цикле.
        bool hasOutSlots = false;
        bool hasSumSlots = false;
        bool isComplete = false; // hasOutSlots && hasSumSlots

        // Признак «в сумму начисляется константа 1» для конкретного слота не
        // хранится: он живёт в SlotBinding (привязка готовится один раз) и в
        // цикле известен по индексу. Дублировать его здесь — значит хранить
        // вторую правду о том же поле.
    };

    // Сбор вклада разбит на ДВЕ фазы — не для удобства, а потому что так
    // устроен исходный цикл:
    //
    //   фаза 1 (BuildContribution) — флаг группы, уникальные параметры, ключ
    //   строки и СУММИРУЕМЫЕ слоты. Выполняется для КАЖДОГО источника.
    //
    //   фаза 2 (ReadContributionOutputs) — выходные слоты и ключ выхода.
    //   Выполняется ТОЛЬКО для первого представителя ключа, потому что
    //   decides.ContainsKey (key) в исходном цикле стоит именно после чтения
    //   сумм, а ключ известен лишь с конца фазы 1.
    //
    // Если слить фазы, выходные слоты будут читаться у каждого источника, а не
    // у первого представителя. Это изменит ЧИСЛО чтений и, что важнее, список
    // непрочитанных полей выхода: неполный выход второго источника попал бы в
    // отчёт как ошибка, хотя раньше молча игнорировался. Поэтому две фазы.
    //
    // Порядок чтения сохранён: флаг -> уникальные -> суммы -> выход.
    //
    // reader передаётся владельцем правила (R5.4: один reader на правило,
    // читателей много). Вклад возвращается по значению: он живёт один проход
    // цикла, копия дешевле хранения в словаре вкладов (его и нет — см. выше).
    //
    // notFoundParame/notFoundUnic — счётчики НА ВСЁ ПРАВИЛО. Вклад их только
    // ЧИТАЕТ, чтобы не повторять сообщение для уже сообщённого поля, и не
    // меняет: политика повторов остаётся в PlanRuleRows, вклад — описание.
    RuleContribution BuildContribution (const API_Guid &elemguid,
                                        UInt32 groupIndex,
                                        const GroupSpec &group,
                                        const GroupSlotBinding &binding,
                                        const SpecValueReader &reader,
                                        const ParamDict &notFoundParame,
                                        const ParamDict &notFoundUnic);

    // Фаза 2: выходные слоты и ключ выхода. Вызывается только когда ключа ещё
    // нет в словаре элементов.
    void ReadContributionOutputs (const API_Guid &elemguid,
                                  const GroupSpec &group,
                                  const GroupSlotBinding &binding,
                                  const SpecValueReader &reader,
                                  FormatString &fstr,
                                  RuleContribution &contribution);

    // Статус по фактическим размерам вклада и размерам схемы. Вынесено из
    // вклада, чтобы правило «статус = функция размеров» было в одном месте.
    ContributionStatus ClassifyContribution (const RuleContribution &contribution,
                                             UInt32 schemaOutSlots,
                                             UInt32 schemaSumSlots);

    // ---- Раскладка вклада в итоговую строку (R6.3) ----

    // Что произошло с ключом при добавлении вклада.
    enum class RowAddition {
        Created,       // Ключа не было: строка создана и добавлена
        Merged,        // Ключ был: вклад слит с существующей строкой
        SchemaMismatch // Первый представитель не наполнил схему: строка НЕ добавлена
    };

    // Суммирование вклада в СУЩЕСТВУЮЩУЮ строку. Проверяемая единица: тест
    // может собрать две строки с разной длиной массивов и сравнить результат
    // напрямую, без словаря элементов и без модели.
    //
    // Поведение неполных массивов СОХРАНЕНО ДОСЛОВНО и не является исправлением:
    //   - складываются только первые nsumm = MIN(длин) слотов;
    //   - слот складывается, только если isValid у ОБЕИХ сторон, иначе
    //     остаётся как есть (в том числе остаётся невалидным);
    //   - слоты сверх nsumm не трогаются вообще.
    // Строгая проверка «длины равны, иначе ошибка» здесь была бы «улучшением»,
    // меняющим результат, — этого R6.3 делать не должен (см. F в плане).
    void SumContributionIntoRow (Element &row, const RuleContribution &contribution);

    // Добавление вклада в словарь строк. Самостоятельная единица: словарь
    // элементов — единственное, что было недоступно вкладу, и теперь раскладка
    // отдаёт его наружу одной операцией.
    //
    // Что делает функция:
    //   Merged   — дописывает источник вкладом и вызывает SumContributionIntoRow.
    //   Created  — собирает строку из вклада (выходные слоты к этому моменту
    //              уже прочитаны фазой 2), КОПИРУЕТ признаки правила,
    //              добавляет источник и строку в словарь.
    //   SchemaMismatch — ничего не добавляет, строка отбрасывается. Решение о
    //              том, что с этим делать (отметить элемент, обнулить счётчик),
    //              остаётся у вызывающей: это политика, а не раскладка.
    //
    // ПОРЯДОК, который обязан сохраниться (иначе поменяется результат):
    //   1. при Created запись outParam[keyOut] = key делается ДО проверки
    //      схемы — то есть попадает в словарь даже для отброшенной строки;
    //   2. при Merged источник дописывается ДО суммирования;
    //   3. выходные слоты берутся из вклада как есть; пересчёта и фильтрации
    //      не производится.
    RowAddition AddContributionToRow (ElementDict &rows,
                                      const RuleContribution &contribution,
                                      const SpecRule &rule,
                                      UInt32 schemaOutSlots,
                                      UInt32 schemaSumSlots,
                                      GS::HashTable<GS::UniString, GS::UniString> &outParam);
} // namespace Spec
#endif // SPECPLANNING_HPP
